import { readFile } from "node:fs/promises";
import { isNotFound, writeFileAtomic } from "../util/fs.js";
import { withLock } from "../util/lock.js";
import { generateKey } from "../util/random.js";
import { registerSecret } from "../util/redact.js";
import { statePaths } from "./paths.js";

export const SECRETS_FILE_MODE = 0o600;

const NAME_RE = /^[A-Z_][A-Z0-9_]*$/;

function assertName(name: string): void {
  if (!NAME_RE.test(name)) throw new Error(`Invalid secret name "${name}": use UPPER_SNAKE_CASE.`);
}

function parse(text: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const value = trimmed.slice(eq + 1);
    out.set(trimmed.slice(0, eq).trim(), value);
    registerSecret(value);
  }
  return out;
}

function serialize(secrets: Map<string, string>): string {
  const lines = ["# Generated by ownstack. Never commit or share this file."];
  for (const [k, v] of secrets) lines.push(`${k}=${v}`);
  return lines.join("\n") + "\n";
}

/** Read every secret; each value is registered with the redactor. */
export async function readSecrets(cwd: string): Promise<Map<string, string>> {
  try {
    return parse(await readFile(statePaths(cwd).secretsFile, "utf8"));
  } catch (err) {
    if (isNotFound(err)) return new Map();
    throw err;
  }
}

export async function writeSecrets(cwd: string, secrets: Map<string, string>): Promise<void> {
  await writeFileAtomic(statePaths(cwd).secretsFile, serialize(secrets), SECRETS_FILE_MODE);
}

export async function getSecret(cwd: string, name: string): Promise<string | undefined> {
  assertName(name);
  return (await readSecrets(cwd)).get(name);
}

export async function setSecret(cwd: string, name: string, value: string): Promise<void> {
  assertName(name);
  if (!value || /[\r\n]/.test(value)) throw new Error(`Secret ${name} must be a non-empty single-line value.`);
  registerSecret(value);
  await withLock(statePaths(cwd).secretsFile, async () => {
    const secrets = await readSecrets(cwd);
    secrets.set(name, value);
    await writeSecrets(cwd, secrets);
  });
}

/** Return the stored secret, generating and persisting one if absent. */
export async function ensureSecret(
  cwd: string,
  name: string,
  generator: () => string = generateKey,
): Promise<string> {
  assertName(name);
  return withLock(statePaths(cwd).secretsFile, async () => {
    const secrets = await readSecrets(cwd);
    const existing = secrets.get(name);
    if (existing) return existing;
    const value = generator();
    if (!value || /[\r\n]/.test(value)) throw new Error(`Generated secret ${name} is empty or multi-line.`);
    registerSecret(value);
    secrets.set(name, value);
    await writeSecrets(cwd, secrets);
    return value;
  });
}
